/**
 * Turns docs/muuv/redirects.csv (old muuv.dk path → Trenodo path) into
 * lib/muuv/redirects-map.mjs, the lookup the Worker uses. The CSV stays
 * the one place to edit: change a target there, run this, commit both.
 *
 * Usage: node scripts/build-muuv-redirects.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const csv = readFileSync(path.join(root, "docs/muuv/redirects.csv"), "utf8");

/** A small CSV reader: quoted fields may hold commas and doubled quotes. */
function parse(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      if (row.some((value) => value !== "")) rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field || row.length) rows.push([...row, field]);
  return rows;
}

const [header, ...rows] = parse(csv);
const col = (name) => header.indexOf(name);
const map = {};
for (const row of rows) {
  const from = row[col("old_path")];
  const to = row[col("redirect_to")];
  if (!from?.startsWith("/") || !to?.startsWith("/")) throw new Error(`Bad row: ${row.join(",")}`);
  map[from] = to;
}

const out = `// Generated by scripts/build-muuv-redirects.mjs from docs/muuv/redirects.csv.
// Don't edit by hand: change the CSV and run the script again.

/** Old muuv.dk path → Trenodo path. */
export const MUUV_EXACT = ${JSON.stringify(map, null, 2)};
`;
writeFileSync(path.join(root, "lib/muuv/redirects-map.mjs"), out);
console.log(`${Object.keys(map).length} redirects written to lib/muuv/redirects-map.mjs`);
